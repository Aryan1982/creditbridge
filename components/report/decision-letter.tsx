import { DECISION_LABEL, fmtDate, inr, personaLabel, STATUS_LABEL } from "@/lib/format";
import type { StoredReport } from "@/lib/store";

/** Print-only document rendered by window.print() from the report page. */
export function DecisionLetter({ data }: { data: StoredReport }) {
  const { report, loan } = data;
  const a = report.applicant;
  const r = report.risk;
  const aff = report.affordability;
  const issued = fmtDate(data.createdAt.slice(0, 10));
  const ref = `CB-${data.createdAt.replace(/\D/g, "").slice(2, 14)}`;

  return (
    <article className="hidden text-[11pt] leading-relaxed text-black print:block">
      <header className="flex items-start justify-between border-b border-black pb-4">
        <div>
          <p className="text-[16pt] font-semibold tracking-tight">CreditBridge</p>
          <p className="text-[9pt] text-zinc-600">Cash-flow based credit assessment</p>
        </div>
        <div className="text-right text-[9pt] text-zinc-700">
          <p>Reference {ref}</p>
          <p>Issued {issued}</p>
        </div>
      </header>

      <h1 className="mt-8 text-[15pt] font-semibold">Credit decision letter</h1>
      <p className="mt-4">Dear {a.name},</p>
      <p className="mt-3">
        Thank you for requesting a credit assessment for a loan of {inr(loan.amount)} over {loan.tenure_months} months. We reviewed{" "}
        {a.transaction_count.toLocaleString("en-IN")} transactions from your bank account between {fmtDate(a.start_date)} and {fmtDate(a.end_date)}.
      </p>

      <table className="mt-6 w-full border-collapse text-[10.5pt]">
        <tbody>
          {[
            ["Decision", DECISION_LABEL[r.decision]],
            ["Credit score", `${r.score} out of 900 (band ${r.band})`],
            ["Requested EMI", `${inr(aff.requested_emi)} per month`],
            ["Affordable EMI", `${inr(aff.max_emi)} per month`],
            ["Recommended loan amount", `${inr(aff.recommended_amount)} over ${aff.tenure_months} months at ${aff.rate_pct}% a year`],
            ["Statement authenticity", STATUS_LABEL[report.integrity.status]],
            ["Applicant profile", personaLabel(a.persona)],
          ].map(([k, v]) => (
            <tr key={k} className="border-b border-zinc-300">
              <th scope="row" className="w-[40%] py-2 pr-4 text-left font-medium text-zinc-700">
                {k}
              </th>
              <td className="py-2">{v}</td>
            </tr>
          ))}
        </tbody>
      </table>

      <h2 className="mt-8 text-[12pt] font-semibold">Summary</h2>
      <p className="mt-2">{report.summary.en}</p>

      <h2 className="mt-6 text-[12pt] font-semibold">Main reasons for this decision</h2>
      <ol className="mt-2 list-decimal space-y-1.5 pl-5">
        {r.reasons.map((x) => (
          <li key={x.key}>
            <span className="font-medium">{x.label}</span> ({x.direction === "helps" ? "in your favour" : "against"}): {x.detail}
          </li>
        ))}
      </ol>

      {report.improvements.length > 0 && (
        <>
          <h2 className="mt-6 text-[12pt] font-semibold">How you can improve</h2>
          <ol className="mt-2 list-decimal space-y-1.5 pl-5">
            {report.improvements.map((x) => (
              <li key={x.key}>
                {x.label}: currently {x.current}, target {x.target}. Projected score {x.score_after}.
              </li>
            ))}
          </ol>
        </>
      )}

      <p className="mt-10 border-t border-zinc-300 pt-3 text-[8.5pt] text-zinc-600">
        This letter is generated by CreditBridge, a decision-support tool, from the bank statement data you provided. It is not a loan
        offer or a sanction. Your statement was analysed in memory and has not been stored.
      </p>
    </article>
  );
}
